#!/usr/bin/env python3
"""Collect license/notice texts for linked Go packages, without reclassifying them."""

import argparse
import json
from pathlib import Path
import re
import subprocess
import sys


def go(*args):
    return subprocess.check_output(["go", *args], text=True)


def generate():
    raw = go("list", "-deps", "-json", "./cmd/restrictedsql-mcp")
    decoder = json.JSONDecoder()
    modules = {}
    pos = 0
    while pos < len(raw):
        while pos < len(raw) and raw[pos].isspace():
            pos += 1
        if pos == len(raw):
            break
        package, pos = decoder.raw_decode(raw, pos)
        module = package.get("Module")
        if not module or module.get("Main"):
            continue
        if module.get("Replace"):
            raise RuntimeError("Resolve module replacements before generating release notices")
        key = (module["Path"], module["Version"])
        root = Path(module["Dir"])
        entry = modules.setdefault(key, (root, set()))
        directory = Path(package["Dir"])
        while directory.is_relative_to(root):
            entry[1].add(directory)
            if directory == root:
                break
            directory = directory.parent

    output = [
        "Third-party notices for restricted-sql-mcp\n",
        "Generated by scripts/update-third-party-notices.py from the linked Go dependency graph.\n",
        "Each dependency retains its original license. These texts do not relicense dependencies.\n",
    ]
    goroot = Path(go("env", "GOROOT").strip())
    output += ["\n=== Go runtime ===\n", (goroot / "LICENSE").read_text()]
    notice_name = re.compile(r"^(LICENSE|LICENCE|COPYING|COPYRIGHT|NOTICE)([._-].*)?$", re.I)
    for (name, version), (root, directories) in sorted(modules.items()):
        files = set()
        for directory in directories:
            for file in directory.iterdir():
                if file.is_file() and notice_name.fullmatch(file.name) and file.suffix not in {".go", ".json"}:
                    files.add(file)
        if not files:
            raise RuntimeError(f"No license or notice found for {name}@{version}")
        output.append(f"\n=== {name}@{version} ===\n")
        for file in sorted(files):
            output += [f"\n--- {file.relative_to(root)} ---\n", file.read_text().rstrip() + "\n"]
    return "".join(output)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = Path("THIRD_PARTY_NOTICES")
    expected = generate()
    if args.check:
        if not path.exists() or path.read_text() != expected:
            sys.exit("THIRD_PARTY_NOTICES is stale; run python3 scripts/update-third-party-notices.py")
        print("Third-party notices match the linked dependency graph")
    else:
        path.write_text(expected)
        print(f"Wrote {path}")


if __name__ == "__main__":
    main()
